  OK_200: 200, // Успешный GET/PUT/PATCH — запрос выполнен, есть тело ответа
  CREATED_201: 201, // Успешный POST — новая сущность создана (обычно возвращают созданный объект)
  NO_CONTENT_204: 204, // Успешно, но возвращать нечего (например DELETE) — тело ответа должно быть пустым

  // ─── 4xx Client Errors ─────────────────────────
  BAD_REQUEST_400: 400, // Невалидные данные в запросе (не прошла валидация body/params/query)
  NO_AUTH_401: 401, // Не авторизован — токена нет, он невалиден или истёк (нужно залогиниться)
  FORBIDDEN_403: 403, // Авторизован, но доступа к этому ресурсу нет (например, обычный user лезет в admin-роут)
  NOT_FOUND_404: 404, // Ресурс с таким id/путём не существует
  CONFLICT_409: 409, // Конфликт состояния (например, email уже занят при регистрации, дубликат unique-поля)
  UNPROCESSABLE_ENTITY_422: 422, // Синтаксически валидный запрос, но семантически некорректный (реже используют вместо 400, некоторые команды разделяют так: 400 — сломанный JSON/формат, 422 — бизнес-валидация)
  TOO_MANY_REQUESTS_429: 429, // Превышен rate limit — клиент шлёт запросы слишком часто

  // ─── 5xx Server Errors ─────────────────────────
  INTERNAL_SERVER_ERROR_500: 500, // Необработанная ошибка на сервере (баг, упавший query, что-то не предусмотрено try/catch)
