  BAD_GATEWAY_502: 502, // Сервер как прокси получил невалидный ответ от вышестоящего сервиса (например, от микросервиса)
  SERVICE_UNAVAILABLE_503: 503, // Сервер временно недоступен (перегрузка, идёт деплой, технические работы)
  GATEWAY_TIMEOUT_504: 504, // Вышестоящий сервис не ответил вовремя (таймаут при обращении к БД/другому микросервису)
